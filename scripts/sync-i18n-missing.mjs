function mergeLocale(code) {
  const file = path.join(localesDir, `${code}.json`);
  const current = JSON.parse(fs.readFileSync(file, 'utf8'));
  const next = { ...current };
  let added = 0;
  for (const [k, v] of Object.entries(en)) {
    if (!(k in next)) {
      next[k] = (overrides[code] && overrides[code][k]) || v;
      added++;
    } else if (overrides[code] && overrides[code][k]) {
      next[k] = overrides[code][k];
    }
  }
  // Ensure all override keys applied even if already present with English stubs
  if (overrides[code]) {
    for (const [k, v] of Object.entries(overrides[code])) {
      next[k] = v;
    }
  }
  // Prefer Spanish company names for shared identity keys already ok
  fs.writeFileSync(file, JSON.stringify(next, null, 2) + '\n');
  return { file: `${code}.json`, keys: Object.keys(next).length, added };
}

